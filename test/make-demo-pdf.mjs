/**
 * Generate a small multi-page demo PDF (test fixture) with raw PDF syntax:
 *   node test/make-demo-pdf.mjs [out]
 * Three pages of Helvetica ASCII text — enough for viewer rendering, text
 * selection and find checks. Output defaults to test/fixtures/demo.pdf.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(process.argv[2] ?? join(here, 'fixtures', 'demo.pdf'))

const PAGE_W = 612 // US Letter
const PAGE_H = 792
/** Escape for a PDF literal string: backslash, parens. */
const esc = text => text.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)')

const pages = [
  {
    title: 'PdfCraft Demo Report',
    lines: [
      'The quick brown fox jumps over the lazy dog.',
      'This page exists to check rendering, text selection and find.',
      'Try searching for the word fox from the reader toolbar.',
    ],
  },
  {
    title: 'Quarterly Numbers',
    lines: [
      'Revenue grew 42 percent quarter over quarter.',
      'The fox and the hound walked ten miles along the ridge.',
      'Operating margin held steady at 18 percent.',
    ],
  },
  {
    title: 'Notes',
    lines: [
      'This demo embeds no fonts, so it ships ASCII text only.',
      'The fox sleeps under the pine tree at the end of page three.',
      'Generated by test/make-demo-pdf.mjs for end-to-end verification.',
    ],
  },
]

/** Content stream for one page: 24pt title + 12pt lines, top-down. */
function contentStream(page) {
  const parts = [`BT /F1 24 Tf 72 720 Td (${esc(page.title)}) Tj ET`]
  let y = 688
  for (const line of page.lines) {
    parts.push(`BT /F1 12 Tf 72 ${y} Td (${esc(line)}) Tj ET`)
    y -= 20
  }
  return parts.join('\n')
}

// Object numbering: 1 catalog, 2 pages tree, per page i (0-based):
// page = 3 + i*2, contents = 4 + i*2, font = 3 + pages.length*2.
const objects = new Map()
objects.set(1, '<< /Type /Catalog /Pages 2 0 R >>')
const kids = pages.map((_, i) => `${3 + i * 2} 0 R`).join(' ')
objects.set(2, `<< /Type /Pages /Kids [${kids}] /Count ${pages.length} >>`)
pages.forEach((page, i) => {
  const pageId = 3 + i * 2
  const contentId = 4 + i * 2
  objects.set(pageId, `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_W} ${PAGE_H}] /Contents ${contentId} 0 R /Resources << /Font << /F1 ${3 + pages.length * 2} 0 R >> >> >>`)
  const stream = contentStream(page)
  objects.set(contentId, `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`)
})
objects.set(3 + pages.length * 2, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>')

// Serialize with a correct xref table (byte offsets).
const chunks = ['%PDF-1.4\n']
const offsets = []
const maxId = Math.max(...objects.keys())
for (let id = 1; id <= maxId; id++) {
  offsets[id] = chunks.join('').length
  chunks.push(`${id} 0 obj\n${objects.get(id)}\nendobj\n`)
}
const xrefStart = chunks.join('').length
let xref = `xref\n0 ${maxId + 1}\n0000000000 65535 f \n`
for (let id = 1; id <= maxId; id++) {
  xref += `${String(offsets[id]).padStart(10, '0')} 00000 n \n`
}
xref += `trailer\n<< /Size ${maxId + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`
chunks.push(xref)

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, chunks.join(''), 'latin1')
console.log(`[make-demo-pdf] wrote ${out} (${pages.length} pages)`)
